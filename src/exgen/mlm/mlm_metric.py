import torch
import numpy as np
import torch.nn.functional as F
from transformers import AutoModelForMaskedLM, AutoTokenizer
from typing import List, Dict, Any

class MaskedLMRanker:
    """
    A metric module that evaluates how well a sentence exemplifies a target word
    using Masked Language Modeling (MLM).

    It works by masking the target word in the provided sentence and calculating
    the probability of the model predicting the true target word in that context.
    Higher scores indicate that the context strongly predicts the target word.
    """

    def __init__(self, model_name: str):
        """
        Initializes the MaskedLMRanker with a specific HuggingFace model.

        Args:
            model_name (str): The HuggingFace model hub name for the MLM model.
                              Examples: "roberta-large" (English), "google/muril-base-cased" (Hindi).
        """
        self.model_name = model_name
        self.tokenizer = AutoTokenizer.from_pretrained(model_name)
        self.model = AutoModelForMaskedLM.from_pretrained(model_name)
        self.model.eval()
        self.mask_token = self.tokenizer.mask_token

    def get_exemplification_score(self, sentence: str, target_word: str) -> Dict[str, Any]:
        """
        Calculates the probability of the target word appearing in the given sentence context.

        Args:
            sentence (str): The context sentence.
            target_word (str): The word within the sentence to evaluate.

        Returns:
            Dict[str, Any]: A dictionary containing:
                - status (str): "SUCCESS" or "failure"
                - score (float): Normalized probability score (higher is better)
                - log_prob (float): Mean log probability across all occurrences
                - tokens (List[str]): The tokens that were matched and evaluated
                - reason (str): Explanation if status is "failure"
        """
        # 1. Identify where the word is and handle multi-tokenization
        candidate_forms = set([
            target_word,
            target_word.lower(),
            target_word.capitalize(),
            " " + target_word,
            " " + target_word.lower(),
            " " + target_word.capitalize()
        ])

        target_variants = []
        seen_id_tuples = set()

        for form in candidate_forms:
            toks = self.tokenizer.tokenize(form)
            ids = tuple(self.tokenizer.convert_tokens_to_ids(toks))
            if ids not in seen_id_tuples:
                seen_id_tuples.add(ids)
                target_variants.append((toks, list(ids)))

        # 2. Tokenize whole sentence
        inputs = self.tokenizer(sentence, return_tensors="pt")
        input_ids = inputs["input_ids"][0]

        # 3. Find all occurrences of the target word in the tokenized sentence
        occurrences = []
        for (toks, t_ids) in target_variants:
            n = len(t_ids)
            for i in range(len(input_ids) - n + 1):
                if input_ids[i : i + n].tolist() == t_ids:
                    occurrences.append((list(range(i, i + n)), t_ids))

        if not occurrences:
            return {
                "status": "failure",
                "reason": f"target_word '{target_word}' not found in the tokenized sentence."
            }

        # 4. Create masked version of the sentence
        masked_input_ids = input_ids.clone()
        for (idx_list, _) in occurrences:
            for idx in idx_list:
                masked_input_ids[idx] = self.tokenizer.mask_token_id

        # 5. Model Inference
        with torch.no_grad():
            outputs = self.model(
                masked_input_ids.unsqueeze(0),
                attention_mask=inputs["attention_mask"]
            )
            logits = outputs.logits[0]  # shapes: [seq_len, vocab_size]

        # 6. Calculate Probability (log_softmax for numerical stability)
        log_probs = F.log_softmax(logits, dim=-1)
        total_log_prob = 0.0
        total_tokens_evaluated = 0

        for (idx_list, t_ids) in occurrences:
            for i, token_idx in enumerate(idx_list):
                target_token_id = t_ids[i]
                token_log_prob = log_probs[token_idx, target_token_id].item()
                total_log_prob += token_log_prob
                total_tokens_evaluated += 1

        # Normalized score - mean log probability across all occurrences
        score = total_log_prob / total_tokens_evaluated

        return {
            "status": "SUCCESS",
            "score": np.exp(score),
            "log_prob": score,
            "tokens": [t for (toks, _) in occurrences[:1] for t in toks]
        }

    def rerank(self, candidates: List[str], target_word: str) -> List[Dict[str, Any]]:
        """
        Scores a list of candidate sentences and returns them sorted from best to worst.

        Args:
            candidates (List[str]): A list of sentences containing the target word.
            target_word (str): The target word to evaluate across the sentences.

        Returns:
            List[Dict[str, Any]]: A list of dictionaries containing the original sentence
                                  and its evaluation metrics, sorted by highest score first.
        """
        results = []
        for sent in candidates:
            res = self.get_exemplification_score(sent, target_word)
            if res["status"] == "SUCCESS":
                results.append({"sentence": sent, **res})
            else:
                print(f"[WARN] Could not score: '{sent[:60]}' - {res.get('reason')}")

        # Sort by score (highest first)
        results.sort(key=lambda x: x["score"], reverse=True)
        return results

    def get_best_sentence(self, candidates: List[str], target_word: str) -> str:
        """
        Evaluates a list of candidates and returns only the sentence
        that best exemplifies the target word.

        Args:
            candidates (List[str]): A list of sentences containing the target word.
            target_word (str): The target word to evaluate.

        Returns:
            str: The single best sentence, or an empty string if evaluation fails.
        """
        ranked_results = self.rerank(candidates, target_word)

        if ranked_results:
            return ranked_results[0]["sentence"]

        return ""


if __name__ == "__main__":
    # Initialize the metric module (Downloads model on first run)
    print("Loading model...")
    english_metric = MaskedLMRanker("roberta-large")

    target = "bank"
    candidates = [
        "I went to the bank to deposit my paycheck.",
        "The fisherman sat on the river bank.",
        "I will meet you near the bank.",
        "He had to bank on his friend's help to finish the job."
    ]

    # 1. Test getting the single best sentence
    best_match = english_metric.get_best_sentence(candidates, target)
    print(f"\n--- Best Sentence for '{target}' ---")
    print(f"'{best_match}'")

    # 2. Test the full rerank list to see the scores
    print(f"\n--- Full Ranked Results ---")
    ranked_sentences = english_metric.rerank(candidates, target)
    for i, res in enumerate(ranked_sentences):
        print(f"{i+1}. {res['sentence']}\n   [Score: {res['score']:.4f}]")

